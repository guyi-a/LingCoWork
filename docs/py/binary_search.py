# 69. x 的平方根 (Sqrt(x))
# 难度: 简单 (Easy)
# 链接: https://leetcode.cn/problems/sqrtx/
#
# 描述:
# 给定一个非负整数 x，返回 x 的算术平方根。
# 因为返回值是整数，小数部分将被舍去；不能使用内置指数函数或运算符。
#
# 示例:
#   x = 8
#   输出: 2
#
# 思路提示:
#   - 在整数区间中二分寻找最大的、平方不超过 x 的数
#   - 答案是满足 mid * mid <= x 的最右位置
#   - 在固定宽度整数语言中可用 mid <= x / mid 避免乘法溢出
