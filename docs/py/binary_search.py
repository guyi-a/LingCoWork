# 704. 二分查找 (Binary Search)
# 难度: 简单 (Easy)
# 链接: https://leetcode.cn/problems/binary-search/
#
# 描述:
# 给定一个升序、元素互不重复的整数数组 nums 和一个目标值 target。
# 如果 target 存在于数组中，返回它的下标；否则返回 -1。
#
# 示例:
#   nums = [-1,0,3,5,9,12], target = 9
#   输出: 4
#
# 思路提示:
#   - 标准二分模板，可使用左闭右闭区间 [left, right]
#   - 循环条件、初始边界和更新方式必须保持一致
#   - 左闭右闭: left <= right，排除 mid 时使用 mid + 1 / mid - 1
