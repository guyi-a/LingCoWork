# 153. 寻找旋转排序数组中的最小值
#      (Find Minimum in Rotated Sorted Array)
# 难度: 中等 (Medium)
# 链接: https://leetcode.cn/problems/find-minimum-in-rotated-sorted-array/
#
# 描述:
# 一个升序且元素互不重复的数组经过若干次旋转后得到 nums。
# 返回数组中的最小元素，要求使用 O(log n) 时间复杂度。
#
# 示例:
#   nums = [3,4,5,1,2]
#   输出: 1
#
# 思路提示:
#   - 比较 nums[mid] 和 nums[right]
#   - nums[mid] > nums[right]: 最小值一定在 mid 右侧
#   - 否则最小值位于 [left, mid]，mid 不能被排除
#   - 维护最小值所在的候选区间，通常在 left == right 时结束
# ---------------------------------------------------------------------------

